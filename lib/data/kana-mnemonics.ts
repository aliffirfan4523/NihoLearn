/**
 * Helper to look up an example word & mnemonic for any character.
 */
export function getKanaExample(character: string, romaji: string): KanaExampleItem {
  if (kanaMnemonicMap[character]) {
    return kanaMnemonicMap[character];
  }

  // Graceful intelligent fallback if an unlisted character is encountered
  return {
    character,
    romaji,
    word: character,
    wordRomaji: romaji,
    meaning: `'${romaji.toUpperCase()}' sound in Japanese`,
    emoji: "🇯🇵",
    mnemonic: `${character} is pronounced '${romaji.toUpperCase()}'. Practice writing and repeating its sound aloud!`,
  };
}
